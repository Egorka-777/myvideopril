        /// <summary>Устаревшие тексты описания видео со словом «ССЫЛКА» (не SEO-банк BinoDex / Pocket Option).</summary>
        public static bool IsLegacyLinkStyleBank(IList<string> bank) {
            if (bank == null || bank.Count == 0) return false;
            foreach (string raw in bank) {
                string text = raw ?? "";
                if (text.IndexOf("ССЫЛКА", StringComparison.OrdinalIgnoreCase) >= 0) return true;
                if (text.IndexOf("LINK TO", StringComparison.OrdinalIgnoreCase) >= 0) return true;
            }
            return false;
        }

        public static bool RunSelfTests() {
            if (!ValidateRu(DefaultsRu())) return false;
            if (!ValidateEn(DefaultsEn())) return false;
            var legacy = new List<string> { "👇 ССЫЛКА НА AI БОТ — В ПРОФИЛЕ\n\nКороткий старый текст." };
            if (!IsLegacyLinkStyleBank(legacy)) return false;
            if (IsLegacyLinkStyleBank(DefaultsRu())) return false;
            return true;
        }

        static bool ValidateRu(List<string> bank) {
            if (bank.Count != 20 || bank.Distinct(StringComparer.Ordinal).Count() != 20) return false;
            if (bank.Any(x => !x.StartsWith(HeaderRu, StringComparison.Ordinal))) return false;
            if (bank.Any(x => !x.Contains("Показываю весь процесс:"))) return false;
            if (bank.Any(x => !x.Contains("В видео также разбираем:"))) return false;
            if (bank.Any(x => !x.Contains(BotNoteRu))) return false;
            if (bank.Any(x => !x.Contains(DisclaimerRu))) return false;
            if (bank.Any(x => !x.EndsWith(HashTagsRu, StringComparison.Ordinal))) return false;
            if (bank.Any(x => x.IndexOf("ссылк", StringComparison.OrdinalIgnoreCase) >= 0)) return false;
            if (bank.Any(x => x.Length > 5000)) return false;
            return true;
        }

        static bool ValidateEn(List<string> bank) {
            if (bank.Count != 20 || bank.Distinct(StringComparer.Ordinal).Count() != 20) return false;
            if (bank.Any(x => !x.StartsWith(HeaderEn, StringComparison.Ordinal))) return false;
            if (bank.Any(x => !x.Contains("Here's the full process:"))) return false;
